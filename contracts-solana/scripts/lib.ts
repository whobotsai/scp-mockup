// Shared helpers for every script in this directory -- loading a keypair/IDL/program id,
// building a provider, and reading/writing the manual test flow's state file. Factored out
// once a third script (scripts/test/01-create-campaign.ts) needed the exact same
// keypair/IDL/Anchor.toml loading logic scripts/initialize.ts already had.
"use strict";
import * as fs from "fs";
import * as path from "path";
import * as toml from "@iarna/toml";
import { AnchorProvider, Wallet } from "@coral-xyz/anchor";
import { Connection, Keypair, PublicKey } from "@solana/web3.js";

const ROOT = path.join(__dirname, "..");

export function loadKeypair(keypairPath: string): Keypair {
  const raw = JSON.parse(fs.readFileSync(keypairPath, "utf8"));
  return Keypair.fromSecretKey(Uint8Array.from(raw));
}

export function loadIdl(name: string) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, "target", "idl", `${name}.json`), "utf8"));
}

// Reads the real program id from Anchor.toml's [programs.<cluster>] section -- never the
// placeholder declare_id!() values -- same as scripts/initialize.ts originally had inline.
export function programIdFromAnchorToml(name: string): PublicKey {
  const anchorToml = toml.parse(fs.readFileSync(path.join(ROOT, "Anchor.toml"), "utf8")) as any;
  const cluster = process.env.ANCHOR_CLUSTER || anchorToml.provider?.cluster || "localnet";
  const section = anchorToml.programs?.[cluster];
  if (!section?.[name]) {
    throw new Error(
      `Anchor.toml has no [programs.${cluster}] entry for ${name} -- run anchor keys list and paste it in first (README.md step 1/3).`
    );
  }
  return new PublicKey(section[name]);
}

export function makeProvider(): { provider: AnchorProvider; wallet: Keypair; connection: Connection } {
  const rpcUrl = process.env.SOLANA_RPC_URL;
  const keypairPath = process.env.AUTHORITY_KEYPAIR;
  if (!rpcUrl || !keypairPath) {
    console.error("Set SOLANA_RPC_URL and AUTHORITY_KEYPAIR before running this.");
    process.exit(1);
  }
  const connection = new Connection(rpcUrl, "confirmed");
  const wallet = loadKeypair(keypairPath);
  const provider = new AnchorProvider(connection, new Wallet(wallet), { commitment: "confirmed" });
  return { provider, wallet, connection };
}

// Same role as ../../contracts/deployments/test-campaign.json -- hands state between a
// scripts/test/*.ts flow's own numbered steps. Never committed (generated by running step 1,
// same as the EVM file never being checked in either). `name` defaults to "test-campaign" for
// the original SHO flow (scripts/test/01-create-campaign.ts etc); the SSO flow passes
// "test-campaign-sso" so the two don't clobber each other's state if run back to back.
export function testCampaignPath(name: string = "test-campaign"): string {
  return path.join(ROOT, "deployments", `${name}.json`);
}

export function readTestCampaign(name: string = "test-campaign"): any {
  const p = testCampaignPath(name);
  if (!fs.existsSync(p)) {
    console.error(`No ${p} -- run that flow's own step 1 script first.`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

export function writeTestCampaign(data: any, name: string = "test-campaign") {
  const p = testCampaignPath(name);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, JSON.stringify(data, null, 2));
}
